// (ii) Fused O(1) decode step — launch_kda_decode_step
// ═══════════════════════════════════════════════════════════════════════════

/// One token, one sequence, nonzero initial state: core (pre-o_norm), the
/// o_norm f32 tap and the mutated state, all against
/// kda_ref::recurrent_step + kda_ref::gated_rmsnorm.
void decode_step_case(int heads, uint64_t seed, const char* tag) {
    const KdaParams p = ref_params(heads);
    const int C = p.channels();
    const size_t sn = static_cast<size_t>(heads) * D * D;
    const ScanKernelInputs in = make_scan_kernel_inputs(heads, 1, seed);

    // CPU reference (q/k/v are POST-conv activations — recurrent_step's input).
    KdaState st = KdaState::zeros(p);
    st.s = in.s0;
    std::vector<float> ref_core(C), ref_onorm(C);
    recurrent_step(p, in.q.data(), in.k.data(), in.v.data(), in.raw_g.data(), in.beta.data(),
                   in.a_log.data(), in.dt_bias.data(), st, ref_core.data());
    gated_rmsnorm(p, ref_core.data(), in.g2.data(), in.onorm_w.data(), 1, ref_onorm.data());

    DevBag bag;
    float* state = bag.f32(in.s0);
    float* core = bag.f32z(C);
    float* onorm = bag.f32z(C);
    sl::KdaDecodeStepParams dp{};
    dp.q = bag.f32(in.q);
    dp.k = bag.f32(in.k);
    dp.v = bag.f32(in.v);
    dp.raw_g = bag.bf16(in.raw_g);
    dp.beta = bag.bf16(in.beta);
    dp.g2 = bag.bf16(in.g2);
    dp.a_log = bag.f32(in.a_log);
    dp.dt_bias = bag.f32(in.dt_bias);
    dp.onorm_w = bag.bf16(in.onorm_w);
    dp.state_base = state;
    dp.state_slot_stride = static_cast<int64_t>(sn);
    dp.slots = nullptr;
    dp.core_out = core;
    dp.out_bf16 = nullptr;
    dp.out_f32 = onorm;
    dp.batch = 1;
    dp.num_heads = heads;
    dp.lower_bound = kLowerBound;
    dp.l2_eps = kL2Eps;
    dp.onorm_eps = kONormEps;
    dp.scale = kda_scale();
    lc::launch_kda_decode_step(dp, nullptr);
    ASSERT_EQ(cudaDeviceSynchronize(), cudaSuccess);

    const std::string t(tag);
    expect_close(download<float>(core, C), ref_core, 2e-5, 2e-4, t + " decode core");
    expect_close(download<float>(onorm, C), ref_onorm, 2e-5, 2e-4, t + " decode onorm");
    expect_close(download<float>(state, sn), st.s, 2e-5, 2e-4, t + " decode state");
}

TEST(KdaDecodeKernel, StepMatchesReference) {
    REQUIRES_GPU();
    decode_step_case(4, 45000, "H=4");
}

