        EXPECT_TRUE(bit_equal(download<float>(ra[i], rn), download<float>(rb[i], rn)))
            << "conv split ring_" << tag[i] << " is not bitwise (split @" << split << ")";
    }
}

// The decode kernel is the same arithmetic as one prefill column: five
// sequential single-token decode launches must reproduce a five-token prefill
// BIT-FOR-BIT (outputs and rings). If fast-math scheduling ever makes this
// flaky it is a real finding about the two kernels' SiLU/FMA forms — the
// assert stays EQ deliberately.
TEST(KdaConvKernel, DecodeStepMatchesPrefillColumn) {
    REQUIRES_GPU();
    const int H = 4, T = 5;
    const KdaParams p = ref_params(H);
    const int C = p.channels();
    const size_t n = static_cast<size_t>(T) * C;
    const size_t rn = static_cast<size_t>(C) * 3;

    DevBag bag;
    const __nv_bfloat16* xq = bag.bf16(synth(43001, n, -1.0f, 1.0f, true));
    const __nv_bfloat16* xk = bag.bf16(synth(43002, n, -1.0f, 1.0f, true));
    const __nv_bfloat16* xv = bag.bf16(synth(43003, n, -1.0f, 1.0f, true));
    const __nv_bfloat16* wq = bag.bf16(synth(43004, static_cast<size_t>(C) * 4, -0.5f, 0.5f, true));
    const __nv_bfloat16* wk = bag.bf16(synth(43005, static_cast<size_t>(C) * 4, -0.5f, 0.5f, true));
    const __nv_bfloat16* wv = bag.bf16(synth(43006, static_cast<size_t>(C) * 4, -0.5f, 0.5f, true));
    const auto r0q = ring_ref_to_gpu(synth(43007, rn, -1.0f, 1.0f, true), C);
    const auto r0k = ring_ref_to_gpu(synth(43008, rn, -1.0f, 1.0f, true), C);
    const auto r0v = ring_ref_to_gpu(synth(43009, rn, -1.0f, 1.0f, true), C);

    float* rp[3] = {bag.f32(r0q), bag.f32(r0k), bag.f32(r0v)};  // prefill arm
    float* rd[3] = {bag.f32(r0q), bag.f32(r0k), bag.f32(r0v)};  // decode arm
    float* op[3] = {bag.f32z(n), bag.f32z(n), bag.f32z(n)};
    float* od[3] = {bag.f32z(n), bag.f32z(n), bag.f32z(n)};

    {
        sl::KdaConvPrefillParams cp{};
        cp.x_q = xq; cp.x_k = xk; cp.x_v = xv;
        cp.w_q = wq; cp.w_k = wk; cp.w_v = wv;
        cp.ring_q = rp[0]; cp.ring_k = rp[1]; cp.ring_v = rp[2];
        cp.out_q = op[0]; cp.out_k = op[1]; cp.out_v = op[2];
