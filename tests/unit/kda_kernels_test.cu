// Case B: REAL GLM-5.3-Flash layer-0 KDA tensors (heads {0,17,42,63}) drive
// the gate/conv/o_norm; activations synthetic; raw_g/g2 through the REAL
// f_b/g_b low-rank mats. Zero initial state and rings. Bands start at the CPU
// real-case bands (4e-4 / 4e-3): the low-rank GEMM is recomputed here with
// sequential fp32 dots while the generator used numpy pairwise sums, so a gate
// input can land 1 bf16 ulp apart and the real steep gates (exp(A_log) up to
// 8.2) amplify that — see kda_reference_test.cpp's GoldenRealLayer0Case.
TEST(KdaGoldenReal, FullProtocol) {
    REQUIRES_GPU();
    const GoldenSet g = load_goldens("real_");
    if (g.prefill_core.empty()) GTEST_FAIL() << "goldens missing — run tools/gen_kda_golden.py";

    const std::string fx = "test-data/GLM-5.3-Flash/kda-layer0/";
    const int kRealHeads[kGoldH] = {0, 17, 42, 63};
    const auto a_log_all = load_f32(fx + "A_log.bin", 64);
    const auto dt_bias_all = load_f32(fx + "dt_bias.bin", 8192);
    const auto conv_q_all = load_bf16_as_f32(fx + "q_conv1d_weight.bin", 8192 * 4);
    const auto conv_k_all = load_bf16_as_f32(fx + "k_conv1d_weight.bin", 8192 * 4);
    const auto conv_v_all = load_bf16_as_f32(fx + "v_conv1d_weight.bin", 8192 * 4);
    const auto onorm_w = load_bf16_as_f32(fx + "o_norm_weight.bin", 128);
    const auto f_b = load_bf16_as_f32(fx + "f_b_proj_weight.bin", 8192 * 128);
    const auto g_b = load_bf16_as_f32(fx + "g_b_proj_weight.bin", 8192 * 128);
    if (a_log_all.empty() || f_b.empty()) {
        GTEST_FAIL() << "real layer-0 fixture missing — run tools/fetch_glm53_kda_layer0.py";
    }

    ScanInputs in;
    const size_t n = static_cast<size_t>(kGoldT) * kGoldTok;
    in.q = synth(303, n, -1.0f, 1.0f, true);
    in.k = synth(304, n, -1.0f, 1.0f, true);
    in.v = synth(305, n, -1.0f, 1.0f, true);
    in.beta = synth(306, static_cast<size_t>(kGoldT) * kGoldH, -2.0f, 2.0f, true);
    in.g2.assign(n, 0.0f);
    in.raw_g.assign(n, 0.0f);
    const auto fa = synth(301, static_cast<size_t>(kGoldT) * 128, -1.0f, 1.0f, true);
    const auto ga = synth(302, static_cast<size_t>(kGoldT) * 128, -1.0f, 1.0f, true);
    for (int t = 0; t < kGoldT; ++t) {
        for (int h = 0; h < kGoldH; ++h) {
            const int rh = kRealHeads[h];
            for (int dd = 0; dd < kGoldD; ++dd) {
                const size_t row = static_cast<size_t>(rh) * kGoldD + dd;
                float acc_f = 0, acc_g = 0;
                for (int j = 0; j < 128; ++j) {
                    acc_f += f_b[row * 128 + j] * fa[static_cast<size_t>(t) * 128 + j];
                    acc_g += g_b[row * 128 + j] * ga[static_cast<size_t>(t) * 128 + j];
                }
                const size_t o =
                    static_cast<size_t>(t) * kGoldTok + static_cast<size_t>(h) * kGoldD + dd;
                in.raw_g[o] = bf16_round(acc_f);
                in.g2[o] = bf16_round(acc_g);
            }
        }
    }
    in.a_log.resize(kGoldH);
    in.dt_bias.resize(kGoldTok);
    in.conv_wq.resize(kGoldTok * 4);
    in.conv_wk.resize(kGoldTok * 4);
    in.conv_wv.resize(kGoldTok * 4);
    for (int h = 0; h < kGoldH; ++h) {
        const int rh = kRealHeads[h];
        in.a_log[h] = a_log_all[rh];
        for (int dd = 0; dd < kGoldD; ++dd) {
            in.dt_bias[static_cast<size_t>(h) * kGoldD + dd] =
                dt_bias_all[static_cast<size_t>(rh) * kGoldD + dd];
            for (int j = 0; j < 4; ++j) {
                const size_t src = (static_cast<size_t>(rh) * kGoldD + dd) * 4 + j;
                const size_t dst = (static_cast<size_t>(h) * kGoldD + dd) * 4 + j;
                in.conv_wq[dst] = conv_q_all[src];
                in.conv_wk[dst] = conv_k_all[src];
                in.conv_wv[dst] = conv_v_all[src];
            }
        }
    }
    in.onorm_w = onorm_w;
    // s0 / cs_* stay empty => zero initial recurrent and conv state.
    run_gpu_golden(in, g, 4e-4, 4e-3, "real/gpu");
}

// ═══════════════════════════════════════════════════════════════════════════
// Prefill -> decode continuity: the state handoff GF3.9's hybrid execution
// makes on every request (chunked prefill, then O(1) steps).
// ═══════════════════════════════════════════════════════════════════════════

TEST(KdaPrefillDecodeContinuity, ChunkedThenDecode) {
    REQUIRES_GPU();
    const int H = 2, t_pre = 100, t_dec = 10, T = t_pre + t_dec;
    const KdaParams p = ref_params(H);
    const int C = p.channels();
    const size_t n = static_cast<size_t>(T) * C;
    const size_t rn = static_cast<size_t>(C) * 3;
    const size_t sn = static_cast<size_t>(H) * D * D;
    const ScanInputs in = make_inputs(p, T, 58000);

    // CPU arbiter: the pure recurrent scan of all 110 tokens.
    const ScanResult ref = run_ref_scan(p, ScanPath::kRecurrent, in, T);

    DevBag bag;
    const __nv_bfloat16* xq = bag.bf16(in.q);
    const __nv_bfloat16* xk = bag.bf16(in.k);
    const __nv_bfloat16* xv = bag.bf16(in.v);
    const __nv_bfloat16* wq = bag.bf16(in.conv_wq);
    const __nv_bfloat16* wk = bag.bf16(in.conv_wk);
    const __nv_bfloat16* wv = bag.bf16(in.conv_wv);
    float* rq = bag.f32(ring_ref_to_gpu(in.cs_q, C));
    float* rk = bag.f32(ring_ref_to_gpu(in.cs_k, C));
    float* rv = bag.f32(ring_ref_to_gpu(in.cs_v, C));
    float* cq = bag.f32z(n);
    float* ck = bag.f32z(n);
    float* cv = bag.f32z(n);
    const __nv_bfloat16* rg = bag.bf16(in.raw_g);
    const __nv_bfloat16* bt = bag.bf16(in.beta);
    const __nv_bfloat16* g2 = bag.bf16(in.g2);
    const float* alog = bag.f32(in.a_log);
    const float* dtb = bag.f32(in.dt_bias);
    const __nv_bfloat16* ow = bag.bf16(in.onorm_w);
    float* state = bag.f32(in.s0);
    float* core = bag.f32z(n);
    float* onorm = bag.f32z(n);
    const size_t ws_bytes = lc::kda_prefill_workspace_bytes(t_pre, H);
    void* ws = bag.raw(ws_bytes);

    {
        sl::KdaConvPrefillParams cp{};
        cp.x_q = xq; cp.x_k = xk; cp.x_v = xv;
        cp.w_q = wq; cp.w_k = wk; cp.w_v = wv;
        cp.ring_q = rq; cp.ring_k = rk; cp.ring_v = rv;
        cp.out_q = cq; cp.out_k = ck; cp.out_v = cv;
        cp.t_len = t_pre;
        cp.channels = C;
        lc::launch_kda_conv_prefill(cp, nullptr);
    }
    {
        sl::KdaChunkedScanParams sp{};
        sp.q = cq; sp.k = ck; sp.v = cv;
        sp.raw_g = rg;
        sp.beta = bt;
        sp.a_log = alog;
        sp.dt_bias = dtb;
        sp.state = state;
        sp.core_out = core;
        sp.workspace = ws;
        sp.workspace_bytes = ws_bytes;
        sp.t_len = t_pre;
        sp.num_heads = H;
        sp.lower_bound = kLowerBound;
        sp.l2_eps = kL2Eps;
        sp.scale = kda_scale();
        lc::launch_kda_chunked_scan(sp, nullptr);
    }
    {
        sl::KdaGatedRmsNormParams np{};
        np.core = core;
        np.g2 = g2;
        np.w = ow;
        np.out_bf16 = nullptr;
        np.out_f32 = onorm;
        np.t_len = t_pre;
        np.num_heads = H;
        np.eps = kONormEps;
        lc::launch_kda_gated_rmsnorm(np, nullptr);
    }
    for (int t = t_pre; t < T; ++t) {
        const size_t off = static_cast<size_t>(t) * C;
        sl::KdaConvDecodeParams dp{};
        dp.x_q = xq + off; dp.x_k = xk + off; dp.x_v = xv + off;
        dp.w_q = wq; dp.w_k = wk; dp.w_v = wv;
        dp.ring_q = rq; dp.ring_k = rk; dp.ring_v = rv;
        dp.slots = nullptr;
        dp.ring_slot_stride = static_cast<int64_t>(rn);
        dp.out_q = cq + off; dp.out_k = ck + off; dp.out_v = cv + off;
        dp.batch = 1;
        dp.channels = C;
        lc::launch_kda_conv_decode(dp, nullptr);

        sl::KdaDecodeStepParams sp{};
        sp.q = cq + off; sp.k = ck + off; sp.v = cv + off;
        sp.raw_g = rg + off;
        sp.beta = bt + static_cast<size_t>(t) * H;
        sp.g2 = g2 + off;
        sp.a_log = alog;
        sp.dt_bias = dtb;
        sp.onorm_w = ow;
        sp.state_base = state;
        sp.state_slot_stride = static_cast<int64_t>(sn);
        sp.slots = nullptr;
        sp.core_out = core + off;
        sp.out_bf16 = nullptr;
        sp.out_f32 = onorm + off;
        sp.batch = 1;
        sp.num_heads = H;
        sp.lower_bound = kLowerBound;
        sp.l2_eps = kL2Eps;
        sp.onorm_eps = kONormEps;
        sp.scale = kda_scale();
        lc::launch_kda_decode_step(sp, nullptr);
    }
    ASSERT_EQ(cudaDeviceSynchronize(), cudaSuccess);

    expect_close(download<float>(core, n), ref.core, 3e-5, 3e-4, "continuity core");
    expect_close(download<float>(onorm, n), ref.onorm, 3e-5, 3e-4, "continuity onorm");
    expect_close(download<float>(state, sn), ref.st.s, 3e-5, 3e-4, "continuity state");
    const auto ring_q = ring_gpu_to_ref(download<float>(rq, rn), C);
    for (size_t i = 0; i < rn; ++i) ASSERT_EQ(ring_q[i], ref.cq.ring[i]) << "ring_q @" << i;
}

