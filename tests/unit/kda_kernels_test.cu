// kda_kernels_test.cu — GF3.7: KDA (Kimi Delta Attention) SM120 kernels on GPU.
//
// ── What is under test ──────────────────────────────────────────────────────
// The five launch wrappers in src/compute/kernels/sm120/attention/kda_linear.h
// (kernels: deps/LayerStoRmKernels/csrc/sm120/linear/kda_scan.h):
//   launch_kda_conv_prefill / launch_kda_conv_decode  — width-4 depthwise
//       causal short conv on q/k/v with carried ring state (+ SiLU),
//   launch_kda_chunked_scan                           — chunk-64 WY/UT prefill
//       scan (safe gate, q/k L2 norm, delta rule, fp32 state in place),
//   launch_kda_gated_rmsnorm                          — o_norm for the prefill
//       path,
//   launch_kda_decode_step                            — fused O(1) decode step
//       (gate + norm + decay + delta + rank-1 write + output + o_norm).
//
// ── The specification is the CPU reference, not this file ───────────────────
// tests/unit/kda_reference.h (GF3.6) and the committed goldens under
// test-data/kda-goldens/ (generated by the INDEPENDENT NumPy transcription
// tools/gen_kda_golden.py) are the arbiter. Every GPU number below is judged
// against kda_ref::{conv_prefill, conv_step, recurrent_step, recurrent_scan,
// chunked_scan, gated_rmsnorm} on bit-identical inputs, or against the golden
// fixtures directly. Where the GPU is expected to be BITWISE equal to itself
// (chunk-64 state carry, conv ring carry, slot indirection) the tests assert
// memcmp equality — those are the properties GF3.8's state pool and GF3.12's
// checkpoints stand on, and a tolerance would hide their loss.
//
// ── Tolerance provenance ────────────────────────────────────────────────────
// The kernels build with --use_fast_math, so expf/sigmoid/rsqrtf/silu are the
// CUDA fast-math approximations while the reference calls libm; the chunked
// scan also reassociates the sums the recurrence does sequentially. Every
// comparison therefore uses the reference test's scale-aware band
// (|a-b| <= frac_scale*max|b| + frac_elem*|b|) and PRINTS the measured worst
// case as a "[kda-tol] <label> max_excess=... max_abs=..." line — on pass as
// well as on fail. The bands below are STARTING values carried over from the
// CPU reference test (GF3.6 measured probe); after the first real GPU run the
// [kda-tol] lines say exactly how much headroom each family has and the bands
// are to be tightened to ~10x the observed excess. Do not loosen a band
// without recording the measured number next to it.
//
// Geometry note: head_dim is compile-fixed at 128 in the kernels, so every
// KdaParams here uses head_dim = 128 and only num_heads varies.

