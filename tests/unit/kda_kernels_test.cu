/// The GPU chunked scan against BOTH CPU paths: the chunked reference (same
/// decomposition, so the tighter band) and the recurrent reference (the
/// "obviously right" path, band widened by the WY reassociation).
void chunk_scan_case(int heads, int t_len, uint64_t seed) {
    const KdaParams p = ref_params(heads);
    const int C = p.channels();
    const size_t n = static_cast<size_t>(t_len) * C;
    const size_t sn = static_cast<size_t>(heads) * D * D;
    const ScanKernelInputs in = make_scan_kernel_inputs(heads, t_len, seed);

    KdaState st_chk = KdaState::zeros(p);
    st_chk.s = in.s0;
    std::vector<float> core_chk(n, 0.0f);
    chunked_scan(p, in.q.data(), in.k.data(), in.v.data(), in.raw_g.data(), in.beta.data(),
                 in.a_log.data(), in.dt_bias.data(), t_len, st_chk, core_chk.data());

    KdaState st_rec = KdaState::zeros(p);
    st_rec.s = in.s0;
    std::vector<float> core_rec(n, 0.0f);
    recurrent_scan(p, in.q.data(), in.k.data(), in.v.data(), in.raw_g.data(), in.beta.data(),
                   in.a_log.data(), in.dt_bias.data(), t_len, st_rec, core_rec.data());

    DevBag bag;
    const size_t ws_bytes = lc::kda_prefill_workspace_bytes(t_len, heads);
    float* state = bag.f32(in.s0);
    float* core = bag.f32z(n);
    sl::KdaChunkedScanParams sp{};
    sp.q = bag.f32(in.q);
    sp.k = bag.f32(in.k);
    sp.v = bag.f32(in.v);
    sp.raw_g = bag.bf16(in.raw_g);
    sp.beta = bag.bf16(in.beta);
    sp.a_log = bag.f32(in.a_log);
    sp.dt_bias = bag.f32(in.dt_bias);
    sp.state = state;
    sp.core_out = core;
    sp.workspace = bag.raw(ws_bytes);
    sp.workspace_bytes = ws_bytes;
    sp.t_len = t_len;
    sp.num_heads = heads;
    sp.lower_bound = kLowerBound;
    sp.l2_eps = kL2Eps;
    sp.scale = kda_scale();
    lc::launch_kda_chunked_scan(sp, nullptr);
    ASSERT_EQ(cudaDeviceSynchronize(), cudaSuccess);

    const auto gcore = download<float>(core, n);
    const auto gstate = download<float>(state, sn);
    char lbl[128];
    std::snprintf(lbl, sizeof(lbl), "chunk H=%d T=%d core vs chunked", heads, t_len);
    expect_close(gcore, core_chk, 2e-5, 2e-4, lbl);
    std::snprintf(lbl, sizeof(lbl), "chunk H=%d T=%d state vs chunked", heads, t_len);
    expect_close(gstate, st_chk.s, 2e-5, 2e-4, lbl);
    std::snprintf(lbl, sizeof(lbl), "chunk H=%d T=%d core vs recurrent", heads, t_len);
    expect_close(gcore, core_rec, 3e-5, 3e-4, lbl);
    std::snprintf(lbl, sizeof(lbl), "chunk H=%d T=%d state vs recurrent", heads, t_len);
    expect_close(gstate, st_rec.s, 3e-5, 3e-4, lbl);
}

