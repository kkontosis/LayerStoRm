// ═══════════════════════════════════════════════════════════════════════════
// Chunk-64 state carry — the BITWISE property GF3.8 / GF3.12 stand on
// ═══════════════════════════════════════════════════════════════════════════

struct CarryArms {
    std::vector<float> core_one, state_one, core_split, state_split;
};

/// One-shot launch of `t_len` vs two launches (split + rest) carrying the fp32
/// state through global memory. Each arm gets its OWN zeroed workspace so a
/// workspace-reuse artifact can never masquerade as a carry property.
CarryArms run_carry(int heads, int t_len, int split, uint64_t seed) {
    const KdaParams p = ref_params(heads);
    const int C = p.channels();
    const size_t n = static_cast<size_t>(t_len) * C;
    const size_t sn = static_cast<size_t>(heads) * D * D;
    const ScanKernelInputs in = make_scan_kernel_inputs(heads, t_len, seed);

    DevBag bag;
    const float* q = bag.f32(in.q);
    const float* k = bag.f32(in.k);
    const float* v = bag.f32(in.v);
    const __nv_bfloat16* rg = bag.bf16(in.raw_g);
    const __nv_bfloat16* bt = bag.bf16(in.beta);
    const float* alog = bag.f32(in.a_log);
    const float* dtb = bag.f32(in.dt_bias);
    const size_t ws_bytes = lc::kda_prefill_workspace_bytes(t_len, heads);
    void* ws_one = bag.raw(ws_bytes);
    void* ws_split = bag.raw(ws_bytes);

    float* state_one = bag.f32(in.s0);
    float* core_one = bag.f32z(n);
    float* state_split = bag.f32(in.s0);
    float* core_split = bag.f32z(n);

    auto scan = [&](float* state, float* core, void* ws, int t0, int len) {
        sl::KdaChunkedScanParams sp{};
        sp.q = q + static_cast<size_t>(t0) * C;
        sp.k = k + static_cast<size_t>(t0) * C;
        sp.v = v + static_cast<size_t>(t0) * C;
        sp.raw_g = rg + static_cast<size_t>(t0) * C;
        sp.beta = bt + static_cast<size_t>(t0) * heads;
        sp.a_log = alog;
        sp.dt_bias = dtb;
        sp.state = state;
        sp.core_out = core + static_cast<size_t>(t0) * C;
        sp.workspace = ws;
        sp.workspace_bytes = ws_bytes;
        sp.t_len = len;
        sp.num_heads = heads;
        sp.lower_bound = kLowerBound;
        sp.l2_eps = kL2Eps;
        sp.scale = kda_scale();
        lc::launch_kda_chunked_scan(sp, nullptr);
    };

    scan(state_one, core_one, ws_one, 0, t_len);
    scan(state_split, core_split, ws_split, 0, split);
    scan(state_split, core_split, ws_split, split, t_len - split);
    EXPECT_EQ(cudaDeviceSynchronize(), cudaSuccess);

    CarryArms a;
    a.core_one = download<float>(core_one, n);
    a.state_one = download<float>(state_one, sn);
    a.core_split = download<float>(core_split, n);
    a.state_split = download<float>(state_split, sn);
    return a;
}

// Split at a multiple of 64: identical chunk grid, exact fp32 state round-trip
// through global memory => BIT-FOR-BIT identical. This is the invariant the
// state pool (GF3.8) and checkpoints (GF3.12) are built on; a tolerance here
// would silently permit its loss.
TEST(KdaChunkCarry, Chunk64SplitIsBitwise) {
    REQUIRES_GPU();
    const CarryArms a = run_carry(2, 128, 64, 55000);
    EXPECT_TRUE(bit_equal(a.core_one, a.core_split)) << "core differs across a 64-aligned split";
    EXPECT_TRUE(bit_equal(a.state_one, a.state_split))
        << "state differs across a 64-aligned split";
}

// Same property with a ragged tail (150 = 64 + 86 -> chunks 64|64|22 either
// way): still the same chunk grid, still bitwise.
TEST(KdaChunkCarry, Chunk64SplitTail) {
    REQUIRES_GPU();
    const CarryArms a = run_carry(2, 150, 64, 56000);
    EXPECT_TRUE(bit_equal(a.core_one, a.core_split)) << "core differs across split @64 of 150";
    EXPECT_TRUE(bit_equal(a.state_one, a.state_split)) << "state differs across split @64 of 150";
}

// Split at a NON-multiple of 64 re-grids the chunks (64|36 then 50 instead of
// 64|64|22), so the WY sums reassociate: tolerance-equal but NOT bitwise —
// exactly the CPU reference's ScanSplitBoundaries behaviour. Documenting the
// boundary keeps the engine from assuming arbitrary cut points are free.
TEST(KdaChunkCarry, UnalignedSplitToleranceOnly) {
    REQUIRES_GPU();
    const CarryArms a = run_carry(2, 150, 100, 57000);
    expect_close(a.core_split, a.core_one, 2e-5, 2e-4, "core (unaligned split @100)");
    expect_close(a.state_split, a.state_one, 2e-5, 2e-4, "state (unaligned split @100)");
    EXPECT_FALSE(bit_equal(a.core_one, a.core_split) && bit_equal(a.state_one, a.state_split))
        << "an unaligned split reproduced the one-shot run bitwise — the chunk grid must "
           "have stopped depending on the launch origin; re-derive the carry contract";
}

// ═══════════════════════════════════════════════════════════════════════════
// Goldens — the full 152-token protocol on GPU against the committed fixtures
// ═══════════════════════════════════════════════════════════════════════════

struct GoldenSet {
    std::vector<float> prefill_core, prefill_onorm, state_after_prefill;
    std::vector<float> conv_q, conv_k, conv_v;
    std::vector<float> decode_core, decode_onorm, state_after_decode;
};

constexpr int kGoldT = 152, kGoldPre = 144, kGoldDec = 8, kGoldH = 4, kGoldD = 128;
constexpr size_t kGoldTok = static_cast<size_t>(kGoldH) * kGoldD;  // 512

GoldenSet load_goldens(const std::string& prefix) {
    const std::string base = "test-data/kda-goldens/" + prefix;
    GoldenSet g;
    g.prefill_core = load_f32(base + "prefill_core.bin", kGoldPre * kGoldTok);
    g.prefill_onorm = load_f32(base + "prefill_onorm.bin", kGoldPre * kGoldTok);
    g.state_after_prefill = load_f32(base + "state_after_prefill.bin",
                                     kGoldH * static_cast<size_t>(kGoldD) * kGoldD);
    g.conv_q = load_f32(base + "conv_state_q.bin", kGoldTok * 3);
    g.conv_k = load_f32(base + "conv_state_k.bin", kGoldTok * 3);
    g.conv_v = load_f32(base + "conv_state_v.bin", kGoldTok * 3);
    g.decode_core = load_f32(base + "decode_core.bin", kGoldDec * kGoldTok);
    g.decode_onorm = load_f32(base + "decode_onorm.bin", kGoldDec * kGoldTok);
    g.state_after_decode = load_f32(base + "state_after_decode.bin",
                                    kGoldH * static_cast<size_t>(kGoldD) * kGoldD);
    return g;
}

/// The golden protocol, entirely on the GPU:
///   raw bf16 q/k/v -> conv prefill(144) -> chunked scan(144) -> o_norm(144),
///   then 8 x (conv decode + fused decode step), batch 1.
/// Every output family is checked against the fixture generated by the
/// independent NumPy transcription (tools/gen_kda_golden.py).
void run_gpu_golden(const ScanInputs& in, const GoldenSet& g, double fs, double fe,
                    const std::string& label) {
    const KdaParams p = ref_params(kGoldH);
    const int C = p.channels();  // 512
    const size_t n_all = static_cast<size_t>(kGoldT) * C;
    const size_t rn = static_cast<size_t>(C) * 3;
    const size_t sn = static_cast<size_t>(kGoldH) * kGoldD * kGoldD;

    const std::vector<float> zeros_ring(rn, 0.0f);
    const std::vector<float> zeros_state(sn, 0.0f);

    DevBag bag;
    const __nv_bfloat16* xq = bag.bf16(in.q);
    const __nv_bfloat16* xk = bag.bf16(in.k);
    const __nv_bfloat16* xv = bag.bf16(in.v);
    const __nv_bfloat16* wq = bag.bf16(in.conv_wq);
    const __nv_bfloat16* wk = bag.bf16(in.conv_wk);
    const __nv_bfloat16* wv = bag.bf16(in.conv_wv);
    float* rq = bag.f32(ring_ref_to_gpu(in.cs_q.empty() ? zeros_ring : in.cs_q, C));
    float* rk = bag.f32(ring_ref_to_gpu(in.cs_k.empty() ? zeros_ring : in.cs_k, C));
    float* rv = bag.f32(ring_ref_to_gpu(in.cs_v.empty() ? zeros_ring : in.cs_v, C));
    // Post-conv activations for ALL 152 tokens: the prefill launch fills rows
    // [0,144), each decode step fills its own row.
    float* cq = bag.f32z(n_all);
    float* ck = bag.f32z(n_all);
    float* cv = bag.f32z(n_all);

    const __nv_bfloat16* rg = bag.bf16(in.raw_g);
    const __nv_bfloat16* bt = bag.bf16(in.beta);
    const __nv_bfloat16* g2 = bag.bf16(in.g2);
    const float* alog = bag.f32(in.a_log);
    const float* dtb = bag.f32(in.dt_bias);
    const __nv_bfloat16* ow = bag.bf16(in.onorm_w);
    float* state = bag.f32(in.s0.empty() ? zeros_state : in.s0);
    float* core = bag.f32z(n_all);
    float* onorm = bag.f32z(n_all);
    const size_t ws_bytes = lc::kda_prefill_workspace_bytes(kGoldPre, kGoldH);
    void* ws = bag.raw(ws_bytes);

    {  // conv prefill over the first 144 tokens
        sl::KdaConvPrefillParams cp{};
        cp.x_q = xq; cp.x_k = xk; cp.x_v = xv;
        cp.w_q = wq; cp.w_k = wk; cp.w_v = wv;
        cp.ring_q = rq; cp.ring_k = rk; cp.ring_v = rv;
        cp.out_q = cq; cp.out_k = ck; cp.out_v = cv;
        cp.t_len = kGoldPre;
        cp.channels = C;
        lc::launch_kda_conv_prefill(cp, nullptr);
    }
    {  // chunked scan over the same 144 tokens
        sl::KdaChunkedScanParams sp{};
        sp.q = cq; sp.k = ck; sp.v = cv;
        sp.raw_g = rg;
        sp.beta = bt;
        sp.a_log = alog;
        sp.dt_bias = dtb;
        sp.state = state;
        sp.core_out = core;
        sp.workspace = ws;
        sp.workspace_bytes = ws_bytes;
        sp.t_len = kGoldPre;
        sp.num_heads = kGoldH;
        sp.lower_bound = kLowerBound;
        sp.l2_eps = kL2Eps;
        sp.scale = kda_scale();
        lc::launch_kda_chunked_scan(sp, nullptr);
    }
    {  // gated RMSNorm (f32 tap — bf16 rounding would mask sub-1e-3 error)
        sl::KdaGatedRmsNormParams np{};
        np.core = core;
        np.g2 = g2;
        np.w = ow;
        np.out_bf16 = nullptr;
        np.out_f32 = onorm;
        np.t_len = kGoldPre;
        np.num_heads = kGoldH;
        np.eps = kONormEps;
        lc::launch_kda_gated_rmsnorm(np, nullptr);
    }
    ASSERT_EQ(cudaDeviceSynchronize(), cudaSuccess);

    expect_close(download<float>(core, kGoldPre * kGoldTok), g.prefill_core, fs, fe,
                 label + " prefill_core");
    expect_close(download<float>(onorm, kGoldPre * kGoldTok), g.prefill_onorm, fs, fe,
                 label + " prefill_onorm");
    expect_close(download<float>(state, sn), g.state_after_prefill, fs, fe,
                 label + " state_after_prefill");

    // Conv rings hold the last three RAW inputs: exact, once transposed out of
    // the GPU's [3][C] into the fixture's [C][3].
    const auto ring_q = ring_gpu_to_ref(download<float>(rq, rn), C);
    const auto ring_k = ring_gpu_to_ref(download<float>(rk, rn), C);
    const auto ring_v = ring_gpu_to_ref(download<float>(rv, rn), C);
    expect_close(ring_q, g.conv_q, fs, fe, label + " conv_state_q");
    expect_close(ring_k, g.conv_k, fs, fe, label + " conv_state_k");
    expect_close(ring_v, g.conv_v, fs, fe, label + " conv_state_v");
    for (size_t i = 0; i < rn; ++i) {
        ASSERT_EQ(ring_q[i], g.conv_q[i]) << label << " conv_state_q @" << i;
        ASSERT_EQ(ring_k[i], g.conv_k[i]) << label << " conv_state_k @" << i;
        ASSERT_EQ(ring_v[i], g.conv_v[i]) << label << " conv_state_v @" << i;
    }

    // Decode leg: 8 tokens, one conv-decode + one fused step each.
    for (int t = kGoldPre; t < kGoldT; ++t) {
        const size_t off = static_cast<size_t>(t) * C;
        sl::KdaConvDecodeParams dp{};
        dp.x_q = xq + off; dp.x_k = xk + off; dp.x_v = xv + off;
        dp.w_q = wq; dp.w_k = wk; dp.w_v = wv;
        dp.ring_q = rq; dp.ring_k = rk; dp.ring_v = rv;
        dp.slots = nullptr;
        dp.ring_slot_stride = static_cast<int64_t>(rn);
        dp.out_q = cq + off; dp.out_k = ck + off; dp.out_v = cv + off;
        dp.batch = 1;
        dp.channels = C;
        lc::launch_kda_conv_decode(dp, nullptr);

        sl::KdaDecodeStepParams sp{};
        sp.q = cq + off; sp.k = ck + off; sp.v = cv + off;
        sp.raw_g = rg + off;
        sp.beta = bt + static_cast<size_t>(t) * kGoldH;
        sp.g2 = g2 + off;
        sp.a_log = alog;
        sp.dt_bias = dtb;
        sp.onorm_w = ow;
        sp.state_base = state;
        sp.state_slot_stride = static_cast<int64_t>(sn);
        sp.slots = nullptr;
        sp.core_out = core + off;
        sp.out_bf16 = nullptr;
        sp.out_f32 = onorm + off;
        sp.batch = 1;
        sp.num_heads = kGoldH;
        sp.lower_bound = kLowerBound;
        sp.l2_eps = kL2Eps;
        sp.onorm_eps = kONormEps;
        sp.scale = kda_scale();
