// Post-SiLU outputs vs kda_ref::conv_prefill on the same fp32 inputs, and the
// carried rings BITWISE (they hold raw bf16-valued inputs, so any deviation is
// a layout/indexing bug, not arithmetic). Bands are tight on purpose: the only
// legitimate divergence is fast-math sigmoid inside SiLU.
TEST(KdaConvKernel, PrefillMatchesReference) {
    REQUIRES_GPU();
    const int H = 4, T = 150;
    const KdaParams p = ref_params(H);
    const int C = p.channels();  // 512
    const size_t n = static_cast<size_t>(T) * C;
    const size_t rn = static_cast<size_t>(C) * 3;

    const auto xq = synth(41001, n, -1.0f, 1.0f, true);
    const auto xk = synth(41002, n, -1.0f, 1.0f, true);
    const auto xv = synth(41003, n, -1.0f, 1.0f, true);
    const auto wq = synth(41004, static_cast<size_t>(C) * 4, -0.5f, 0.5f, true);
    const auto wk = synth(41005, static_cast<size_t>(C) * 4, -0.5f, 0.5f, true);
    const auto wv = synth(41006, static_cast<size_t>(C) * 4, -0.5f, 0.5f, true);
    const auto r0q = synth(41007, rn, -1.0f, 1.0f, true);  // [C][3] reference layout
    const auto r0k = synth(41008, rn, -1.0f, 1.0f, true);
    const auto r0v = synth(41009, rn, -1.0f, 1.0f, true);

    // CPU reference (nonzero initial rings).
    ConvState cq = ConvState::zeros(p), ck = ConvState::zeros(p), cv = ConvState::zeros(p);
    cq.ring = r0q;
    ck.ring = r0k;
    cv.ring = r0v;
    std::vector<float> refq(n), refk(n), refv(n);
    conv_prefill(p, xq.data(), T, wq.data(), cq, refq.data());
    conv_prefill(p, xk.data(), T, wk.data(), ck, refk.data());
    conv_prefill(p, xv.data(), T, wv.data(), cv, refv.data());

    DevBag bag;
    sl::KdaConvPrefillParams cp{};
    cp.x_q = bag.bf16(xq);
    cp.x_k = bag.bf16(xk);
    cp.x_v = bag.bf16(xv);
    cp.w_q = bag.bf16(wq);
    cp.w_k = bag.bf16(wk);
    cp.w_v = bag.bf16(wv);
    float* rq = bag.f32(ring_ref_to_gpu(r0q, C));
    float* rk = bag.f32(ring_ref_to_gpu(r0k, C));
    float* rv = bag.f32(ring_ref_to_gpu(r0v, C));
    cp.ring_q = rq;
    cp.ring_k = rk;
    cp.ring_v = rv;
    float* oq = bag.f32z(n);
    float* ok = bag.f32z(n);
    float* ov = bag.f32z(n);
    cp.out_q = oq;
    cp.out_k = ok;
    cp.out_v = ov;
    cp.t_len = T;
    cp.channels = C;
    lc::launch_kda_conv_prefill(cp, nullptr);
    ASSERT_EQ(cudaDeviceSynchronize(), cudaSuccess);

    expect_close(download<float>(oq, n), refq, 1e-6, 1e-5, "conv prefill out_q");
    expect_close(download<float>(ok, n), refk, 1e-6, 1e-5, "conv prefill out_k");
    expect_close(download<float>(ov, n), refv, 1e-6, 1e-5, "conv prefill out_v");

    // Rings: exact (raw inputs round-tripped through fp32), after transposing
    // the GPU's [3][C] back to the reference's [C][3].
    const auto gq = ring_gpu_to_ref(download<float>(rq, rn), C);
    const auto gk = ring_gpu_to_ref(download<float>(rk, rn), C);
    const auto gv = ring_gpu_to_ref(download<float>(rv, rn), C);
    for (size_t i = 0; i < rn; ++i) {
        ASSERT_EQ(gq[i], cq.ring[i]) << "ring_q @" << i;
        ASSERT_EQ(gk[i], ck.ring[i]) << "ring_k @" << i;
        ASSERT_EQ(gv[i], cv.ring[i]) << "ring_v @" << i;
    }
}

// The conv is a pure per-channel ring: splitting a prefill anywhere and
// carrying (ring_q/k/v) through global memory is BITWISE identical to the
// one-shot launch. GPU vs GPU — no reference involved.
TEST(KdaConvKernel, SplitIsBitwise) {
    REQUIRES_GPU();
    const int H = 4, T = 150, split = 97;
    const KdaParams p = ref_params(H);
    const int C = p.channels();
    const size_t n = static_cast<size_t>(T) * C;
    const size_t rn = static_cast<size_t>(C) * 3;

    DevBag bag;
    const __nv_bfloat16* xq = bag.bf16(synth(42001, n, -1.0f, 1.0f, true));
    const __nv_bfloat16* xk = bag.bf16(synth(42002, n, -1.0f, 1.0f, true));
    const __nv_bfloat16* xv = bag.bf16(synth(42003, n, -1.0f, 1.0f, true));
    const __nv_bfloat16* wq = bag.bf16(synth(42004, static_cast<size_t>(C) * 4, -0.5f, 0.5f, true));
    const __nv_bfloat16* wk = bag.bf16(synth(42005, static_cast<size_t>(C) * 4, -0.5f, 0.5f, true));
    const __nv_bfloat16* wv = bag.bf16(synth(42006, static_cast<size_t>(C) * 4, -0.5f, 0.5f, true));
    const auto r0q = ring_ref_to_gpu(synth(42007, rn, -1.0f, 1.0f, true), C);
    const auto r0k = ring_ref_to_gpu(synth(42008, rn, -1.0f, 1.0f, true), C);
    const auto r0v = ring_ref_to_gpu(synth(42009, rn, -1.0f, 1.0f, true), C);

    float* ra[3] = {bag.f32(r0q), bag.f32(r0k), bag.f32(r0v)};
    float* rb[3] = {bag.f32(r0q), bag.f32(r0k), bag.f32(r0v)};
    float* oa[3] = {bag.f32z(n), bag.f32z(n), bag.f32z(n)};
    float* ob[3] = {bag.f32z(n), bag.f32z(n), bag.f32z(n)};

    auto run = [&](float* const* rings, float* const* outs, int t0, int len) {
        sl::KdaConvPrefillParams cp{};
        cp.x_q = xq + static_cast<size_t>(t0) * C;
        cp.x_k = xk + static_cast<size_t>(t0) * C;
        cp.x_v = xv + static_cast<size_t>(t0) * C;
        cp.w_q = wq;
        cp.w_k = wk;
        cp.w_v = wv;
        cp.ring_q = rings[0];
        cp.ring_k = rings[1];
        cp.ring_v = rings[2];
        cp.out_q = outs[0] + static_cast<size_t>(t0) * C;
        cp.out_k = outs[1] + static_cast<size_t>(t0) * C;
        cp.out_v = outs[2] + static_cast<size_t>(t0) * C;
        cp.t_len = len;
        cp.channels = C;
        lc::launch_kda_conv_prefill(cp, nullptr);
    };

    run(ra, oa, 0, T);
    run(rb, ob, 0, split);
    run(rb, ob, split, T - split);
    ASSERT_EQ(cudaDeviceSynchronize(), cudaSuccess);

    const char* tag[3] = {"q", "k", "v"};
    for (int i = 0; i < 3; ++i) {
