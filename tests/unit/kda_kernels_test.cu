// State-slot indirection (GF3.8's paged state pool plugs in here): three
// sequences with DISTINCT states writing through slots = {1,2,0} must equal
// three independent single-sequence runs BITWISE.
TEST(KdaDecodeKernel, SlotIndirection) {
    REQUIRES_GPU();
    const int H = 2, B = 3;
    const KdaParams p = ref_params(H);
    const int C = p.channels();
    const size_t sn = static_cast<size_t>(H) * D * D;
    const std::vector<int> slots = {1, 2, 0};

    DevBag bag;
    const ScanKernelInputs in = make_scan_kernel_inputs(H, B, 47000);  // B "tokens" = B seqs
    // Distinct initial states, one per sequence.
    std::vector<std::vector<float>> s0(B);
    for (int b = 0; b < B; ++b) s0[b] = synth(47100 + b, sn, -1.0f, 1.0f, false);

    std::vector<float> packed(sn * B, 0.0f);
    for (int b = 0; b < B; ++b) {
        std::copy(s0[b].begin(), s0[b].end(),
                  packed.begin() + static_cast<size_t>(slots[b]) * sn);
    }

    const float* q = bag.f32(in.q);
    const float* k = bag.f32(in.k);
    const float* v = bag.f32(in.v);
    const __nv_bfloat16* rg = bag.bf16(in.raw_g);
    const __nv_bfloat16* bt = bag.bf16(in.beta);
    const __nv_bfloat16* g2 = bag.bf16(in.g2);
    const float* alog = bag.f32(in.a_log);
    const float* dtb = bag.f32(in.dt_bias);
    const __nv_bfloat16* ow = bag.bf16(in.onorm_w);

    auto fill = [&](sl::KdaDecodeStepParams& dp) {
        dp.a_log = alog;
        dp.dt_bias = dtb;
        dp.onorm_w = ow;
        dp.state_slot_stride = static_cast<int64_t>(sn);
        dp.out_bf16 = nullptr;
        dp.num_heads = H;
        dp.lower_bound = kLowerBound;
        dp.l2_eps = kL2Eps;
        dp.onorm_eps = kONormEps;
        dp.scale = kda_scale();
    };

    float* bstate = bag.f32(packed);
    float* bcore = bag.f32z(static_cast<size_t>(B) * C);
    float* bonorm = bag.f32z(static_cast<size_t>(B) * C);
    {
        sl::KdaDecodeStepParams dp{};
        fill(dp);
        dp.q = q; dp.k = k; dp.v = v;
        dp.raw_g = rg; dp.beta = bt; dp.g2 = g2;
        dp.state_base = bstate;
        dp.slots = bag.i32(slots);
        dp.core_out = bcore;
        dp.out_f32 = bonorm;
        dp.batch = B;
        lc::launch_kda_decode_step(dp, nullptr);
    }

    std::vector<float*> sstate(B), score(B), sonorm(B);
    for (int b = 0; b < B; ++b) {
        sstate[b] = bag.f32(s0[b]);
        score[b] = bag.f32z(C);
        sonorm[b] = bag.f32z(C);
        sl::KdaDecodeStepParams dp{};
        fill(dp);
        dp.q = q + static_cast<size_t>(b) * C;
        dp.k = k + static_cast<size_t>(b) * C;
        dp.v = v + static_cast<size_t>(b) * C;
        dp.raw_g = rg + static_cast<size_t>(b) * C;
        dp.beta = bt + static_cast<size_t>(b) * H;
        dp.g2 = g2 + static_cast<size_t>(b) * C;
        dp.state_base = sstate[b];
        dp.slots = nullptr;
        dp.core_out = score[b];
        dp.out_f32 = sonorm[b];
        dp.batch = 1;
        lc::launch_kda_decode_step(dp, nullptr);
    }
    ASSERT_EQ(cudaDeviceSynchronize(), cudaSuccess);

    const auto gstate = download<float>(bstate, sn * B);
    const auto gcore = download<float>(bcore, static_cast<size_t>(B) * C);
    const auto gonorm = download<float>(bonorm, static_cast<size_t>(B) * C);
    for (int b = 0; b < B; ++b) {
        const auto s1 = download<float>(sstate[b], sn);
        const auto c1 = download<float>(score[b], C);
        const auto o1 = download<float>(sonorm[b], C);
        const size_t soff = static_cast<size_t>(slots[b]) * sn;
        const size_t coff = static_cast<size_t>(b) * C;
        EXPECT_EQ(std::memcmp(gstate.data() + soff, s1.data(), sn * sizeof(float)), 0)
            << "slot-indirected state differs from the single-sequence run, b=" << b;
        EXPECT_EQ(std::memcmp(gcore.data() + coff, c1.data(), C * sizeof(float)), 0)
            << "slot-indirected core differs, b=" << b;
        EXPECT_EQ(std::memcmp(gonorm.data() + coff, o1.data(), C * sizeof(float)), 0)
            << "slot-indirected onorm differs, b=" << b;
    }
}

// TD-KDA-DECODE-PIPELINE: the 3-stage cp.async state staging changes WHEN
// state bytes move, never WHAT is computed — each lane stages exactly the 16
// bytes it consumes, the FMA/reduction order is untouched, so plain and
// pipelined variants must be BIT-IDENTICAL in state, core, o_norm f32 AND
// bf16 output. Locked at the golden geometry (H=4), the shipped head count
// (H=64) and under batched slot indirection.
void pipeline_bit_identity_case(int heads, int batch, uint64_t seed) {
    const int C = heads * D;
    const size_t sn = static_cast<size_t>(heads) * D * D;
    const ScanKernelInputs in = make_scan_kernel_inputs(heads, batch, seed);
    std::vector<float> packed(sn * static_cast<size_t>(batch));
    for (int b = 0; b < batch; ++b) {
        const auto st = synth(seed + 100 + static_cast<uint64_t>(b), sn,
                              -1.0f, 1.0f, false);
        std::copy(st.begin(), st.end(),
                  packed.begin() + static_cast<size_t>(b) * sn);
    }
    // Reverse slot order so the indirection is exercised too.
    std::vector<int> slots(static_cast<size_t>(batch));
    for (int b = 0; b < batch; ++b) slots[static_cast<size_t>(b)] = batch - 1 - b;
    std::vector<float> arm_state[2];
    std::vector<float> arm_core[2], arm_onorm[2];
    std::vector<__nv_bfloat16> arm_bf16[2];
    for (int arm = 0; arm < 2; ++arm) {
        DevBag bag;
        float* state = bag.f32(packed);
        float* core = bag.f32z(static_cast<size_t>(batch) * C);
        float* onorm = bag.f32z(static_cast<size_t>(batch) * C);
        __nv_bfloat16* obf = bag.bf16z(static_cast<size_t>(batch) * C);
        sl::KdaDecodeStepParams dp{};
        dp.q = bag.f32(in.q);
        dp.k = bag.f32(in.k);
        dp.v = bag.f32(in.v);
        dp.raw_g = bag.bf16(in.raw_g);
        dp.beta = bag.bf16(in.beta);
        dp.g2 = bag.bf16(in.g2);
        dp.a_log = bag.f32(in.a_log);
        dp.dt_bias = bag.f32(in.dt_bias);
        dp.onorm_w = bag.bf16(in.onorm_w);
        dp.state_base = state;
        dp.state_slot_stride = static_cast<int64_t>(sn);
        dp.slots = bag.i32(slots);
        dp.core_out = core;
        dp.out_bf16 = obf;
        dp.out_f32 = onorm;
        dp.batch = batch;
        dp.num_heads = heads;
        dp.lower_bound = kLowerBound;
        dp.l2_eps = kL2Eps;
        dp.onorm_eps = kONormEps;
        dp.scale = kda_scale();
        sl::run_kda_decode_step_variant(dp, nullptr, /*pipeline=*/arm == 1);
        ASSERT_EQ(cudaDeviceSynchronize(), cudaSuccess);
        arm_state[arm] = download<float>(state, packed.size());
        arm_core[arm] = download<float>(core, static_cast<size_t>(batch) * C);
        arm_onorm[arm] =
            download<float>(onorm, static_cast<size_t>(batch) * C);
        arm_bf16[arm] =
            download<__nv_bfloat16>(obf, static_cast<size_t>(batch) * C);
    }
    EXPECT_EQ(std::memcmp(arm_state[0].data(), arm_state[1].data(),
                          arm_state[0].size() * sizeof(float)), 0)
        << "pipeline changed STATE bytes (H=" << heads << " B=" << batch << ")";
    EXPECT_EQ(std::memcmp(arm_core[0].data(), arm_core[1].data(),
                          arm_core[0].size() * sizeof(float)), 0)
        << "pipeline changed core bytes";
    EXPECT_EQ(std::memcmp(arm_onorm[0].data(), arm_onorm[1].data(),
                          arm_onorm[0].size() * sizeof(float)), 0)
        << "pipeline changed o_norm f32 bytes";
    EXPECT_EQ(std::memcmp(arm_bf16[0].data(), arm_bf16[1].data(),
                          arm_bf16[0].size() * sizeof(__nv_bfloat16)), 0)
        << "pipeline changed bf16 output bytes";
}

