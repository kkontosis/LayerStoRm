// ── geometry / hyper-parameters (must mirror the kernel contract) ───────────

constexpr int D = 128;              ///< head_dim, compile-fixed in the kernels
constexpr float kLowerBound = -5.0f;
constexpr float kL2Eps = 1e-6f;
constexpr float kONormEps = 1e-5f;

/// Host-computed scale — the kernels take it as a parameter precisely so the
/// constant is bit-identical to the CPU reference's KdaParams::scale().
float kda_scale() { return 1.0f / std::sqrt(static_cast<float>(D)); }

KdaParams ref_params(int num_heads) {
    KdaParams p;
    p.num_heads = num_heads;
    p.head_dim = D;
    p.lower_bound = kLowerBound;
    p.l2_eps = kL2Eps;
    p.onorm_eps = kONormEps;
    return p;
}

// ── device helpers (conventions from indexer_kpool_test.cu) ─────────────────

/// Owns every device allocation a test makes and cudaFrees them at scope exit.
class DevBag {
  public:
    DevBag() = default;
    DevBag(const DevBag&) = delete;
    DevBag& operator=(const DevBag&) = delete;
    ~DevBag() {
        for (void* p : ptrs_) cudaFree(p);
    }

    template <typename T>
    T* alloc(size_t n) {
        T* d = nullptr;
        EXPECT_EQ(cudaMalloc(&d, std::max<size_t>(n, 1) * sizeof(T)), cudaSuccess);
        ptrs_.push_back(static_cast<void*>(d));
        return d;
    }

    /// fp32 upload.
    float* f32(const std::vector<float>& h) {
        float* d = alloc<float>(h.size());
        EXPECT_EQ(cudaMemcpy(d, h.data(), h.size() * sizeof(float), cudaMemcpyHostToDevice),
                  cudaSuccess);
        return d;
    }
    /// zeroed fp32 buffer.
    float* f32z(size_t n) {
        float* d = alloc<float>(n);
        EXPECT_EQ(cudaMemset(d, 0, std::max<size_t>(n, 1) * sizeof(float)), cudaSuccess);
        return d;
    }
    /// fp32 host values -> bf16 device buffer. Fixture/synth inputs are already
    /// bf16-rounded (kda_ref::bf16_round), so this conversion is exact.
    __nv_bfloat16* bf16(const std::vector<float>& h) {
        std::vector<__nv_bfloat16> tmp(h.size());
        for (size_t i = 0; i < h.size(); ++i) tmp[i] = __float2bfloat16(h[i]);
        __nv_bfloat16* d = alloc<__nv_bfloat16>(tmp.size());
        EXPECT_EQ(cudaMemcpy(d, tmp.data(), tmp.size() * sizeof(__nv_bfloat16),
                             cudaMemcpyHostToDevice),
                  cudaSuccess);
        return d;
    }
    __nv_bfloat16* bf16z(size_t n) {
        __nv_bfloat16* d = alloc<__nv_bfloat16>(n);
        EXPECT_EQ(cudaMemset(d, 0, std::max<size_t>(n, 1) * sizeof(__nv_bfloat16)),
                  cudaSuccess);
        return d;
    }
    int* i32(const std::vector<int>& h) {
        int* d = alloc<int>(h.size());
        EXPECT_EQ(cudaMemcpy(d, h.data(), h.size() * sizeof(int), cudaMemcpyHostToDevice),
                  cudaSuccess);
        return d;
    }
    /// zeroed raw byte buffer (scan workspace).
    void* raw(size_t bytes) {
        void* d = nullptr;
        EXPECT_EQ(cudaMalloc(&d, std::max<size_t>(bytes, 1)), cudaSuccess);
        EXPECT_EQ(cudaMemset(d, 0, std::max<size_t>(bytes, 1)), cudaSuccess);
        ptrs_.push_back(d);
        return d;
    }

  private:
    std::vector<void*> ptrs_;
};

template <typename T>
std::vector<T> download(const void* d, size_t n) {
    std::vector<T> h(n);
    EXPECT_EQ(cudaMemcpy(h.data(), d, n * sizeof(T), cudaMemcpyDeviceToHost), cudaSuccess);
    return h;
}

std::vector<float> download_bf16_as_f32(const void* d, size_t n) {
    const std::vector<__nv_bfloat16> raw = download<__nv_bfloat16>(d, n);
    std::vector<float> h(n);
    for (size_t i = 0; i < n; ++i) h[i] = __bfloat162float(raw[i]);
    return h;
}

/// Conv ring layout bridge: the GPU ring is [3][C] (oldest tap first, one
/// coalesced row per tap), kda_ref::ConvState::ring is its transpose [C][3].
/// The VALUES are identical (the last 3 raw pre-conv inputs).
std::vector<float> ring_ref_to_gpu(const std::vector<float>& ref, int channels) {
    std::vector<float> g(static_cast<size_t>(channels) * 3, 0.0f);
    for (int ch = 0; ch < channels; ++ch) {
        for (int j = 0; j < 3; ++j) {
            g[static_cast<size_t>(j) * channels + ch] = ref[static_cast<size_t>(ch) * 3 + j];
        }
    }
    return g;
}

std::vector<float> ring_gpu_to_ref(const std::vector<float>& gpu, int channels) {
    std::vector<float> r(static_cast<size_t>(channels) * 3, 0.0f);
    for (int ch = 0; ch < channels; ++ch) {
        for (int j = 0; j < 3; ++j) {
            r[static_cast<size_t>(ch) * 3 + j] = gpu[static_cast<size_t>(j) * channels + ch];
        }
    }
    return r;
}

/// Byte-for-byte comparison of two float vectors (bitwise arms).
bool bit_equal(const std::vector<float>& a, const std::vector<float>& b) {
    if (a.size() != b.size()) return false;
    return std::memcmp(a.data(), b.data(), a.size() * sizeof(float)) == 0;
}

// ── comparison (copied from kda_reference_test.cpp, plus a [kda-tol] tap) ───

struct Closeness {
    double max_abs = 0, max_rel_excess = 0;
    size_t worst = 0;
};

// Scale-aware bound: |a_i - b_i| <= frac_scale * max|b| + frac_elem * |b_i|.
Closeness closeness(const std::vector<float>& a, const std::vector<float>& b,
                    double frac_scale, double frac_elem) {
    Closeness c;
    EXPECT_EQ(a.size(), b.size());
    double scale = 0;
    for (float x : b) scale = std::max(scale, std::abs(double(x)));
    if (scale == 0) scale = 1e-30;
    for (size_t i = 0; i < std::min(a.size(), b.size()); ++i) {
        const double d = std::abs(double(a[i]) - double(b[i]));
        const double bound = frac_scale * scale + frac_elem * std::abs(double(b[i]));
        if (d > c.max_abs) c.max_abs = d;
        const double excess = d / bound;
        if (excess > c.max_rel_excess) {
            c.max_rel_excess = excess;
            c.worst = i;
        }
    }
    return c;
}

/// Band check + UNCONDITIONAL measurement tap. The "[kda-tol]" lines are the
/// provenance for tightening the bands after a real GPU run (file header).
void expect_close(const std::vector<float>& a, const std::vector<float>& b, double frac_scale,
                  double frac_elem, const char* label) {
    const Closeness c = closeness(a, b, frac_scale, frac_elem);
    std::printf("[kda-tol] %-44s max_excess=%.4g max_abs=%.4g (bands %g/%g, n=%zu)\n", label,
                c.max_rel_excess, c.max_abs, frac_scale, frac_elem, b.size());
    std::fflush(stdout);
    EXPECT_LE(c.max_rel_excess, 1.0)
        << label << ": max_abs_diff=" << c.max_abs << " at flat index " << c.worst
        << " (gpu=" << (c.worst < a.size() ? a[c.worst] : 0.f)
        << " ref=" << (c.worst < b.size() ? b[c.worst] : 0.f)
        << ", frac_scale=" << frac_scale << ", frac_elem=" << frac_elem << ")";
}

void expect_close(const std::vector<float>& a, const std::vector<float>& b, double frac_scale,
                  double frac_elem, const std::string& label) {
    expect_close(a, b, frac_scale, frac_elem, label.c_str());
}

// ── fixture I/O (copied from kda_reference_test.cpp) ────────────────────────

std::string resolve_test_data(const std::string& rel) {
    namespace fs = std::filesystem;
    const std::vector<std::string> candidates = {
        rel,
        "../" + rel,
        "../../" + rel,
#ifdef LAYERSTORM_SOURCE_DIR
        std::string(LAYERSTORM_SOURCE_DIR) + "/" + rel,
#endif
    };
    for (const auto& c : candidates) {
        if (fs::exists(c)) return c;
    }
    return rel;  // let the open fail with the raw name in the message
}

std::vector<float> load_f32(const std::string& rel, size_t expect_count) {
    const std::string path = resolve_test_data(rel);
    std::ifstream f(path, std::ios::binary | std::ios::ate);
    EXPECT_TRUE(f.good()) << "missing fixture: " << path;
    if (!f.good()) return {};
    const size_t bytes = static_cast<size_t>(f.tellg());
    EXPECT_EQ(bytes, expect_count * 4) << path;
    std::vector<float> v(expect_count);
    f.seekg(0);
    f.read(reinterpret_cast<char*>(v.data()), static_cast<std::streamsize>(bytes));
    return v;
}

std::vector<float> load_bf16_as_f32(const std::string& rel, size_t expect_count) {
    const std::string path = resolve_test_data(rel);
    std::ifstream f(path, std::ios::binary | std::ios::ate);
    EXPECT_TRUE(f.good()) << "missing fixture: " << path;
    if (!f.good()) return {};
    const size_t bytes = static_cast<size_t>(f.tellg());
    EXPECT_EQ(bytes, expect_count * 2) << path;
    std::vector<uint16_t> raw(expect_count);
    f.seekg(0);
    f.read(reinterpret_cast<char*>(raw.data()), static_cast<std::streamsize>(bytes));
    std::vector<float> v(expect_count);
    for (size_t i = 0; i < expect_count; ++i) v[i] = bf16_to_f32(raw[i]);
    return v;
}

// ── deterministic inputs (same splitmix64 streams as the CPU reference and
//    tools/gen_kda_golden.py — the goldens are only meaningful if these agree) ─

std::vector<float> synth(uint64_t seed, size_t n, float lo, float hi, bool round_bf16) {
    std::vector<float> v(n);
    uint64_t s = seed;
    for (auto& x : v) {
        x = splitmix_uniform(s, lo, hi);
        if (round_bf16) x = bf16_round(x);
    }
    return v;
}

/// Full end-to-end input bundle (raw pre-conv activations + all parameters),
/// identical to kda_reference_test.cpp's ScanInputs.
struct ScanInputs {
    std::vector<float> q, k, v, raw_g, g2, beta, a_log, dt_bias;
    std::vector<float> conv_wq, conv_wk, conv_wv, onorm_w, s0, cs_q, cs_k, cs_v;
};

ScanInputs make_inputs(const KdaParams& p, int t_len, uint64_t seed_base) {
    ScanInputs in;
    const size_t n = static_cast<size_t>(t_len) * p.channels();
    const size_t c = p.channels();
    in.q = synth(seed_base + 0, n, -1.0f, 1.0f, true);
    in.k = synth(seed_base + 1, n, -1.0f, 1.0f, true);
    in.v = synth(seed_base + 2, n, -1.0f, 1.0f, true);
    in.raw_g = synth(seed_base + 3, n, -3.0f, 3.0f, true);
    in.g2 = synth(seed_base + 4, n, -2.0f, 2.0f, true);
    in.beta = synth(seed_base + 5, static_cast<size_t>(t_len) * p.num_heads, -2.0f, 2.0f, true);
    in.a_log = synth(seed_base + 6, p.num_heads, -1.0f, 1.5f, false);
    in.dt_bias = synth(seed_base + 7, c, -1.0f, 1.0f, false);
    in.conv_wq = synth(seed_base + 8, c * p.conv_width, -0.5f, 0.5f, true);
    in.conv_wk = synth(seed_base + 9, c * p.conv_width, -0.5f, 0.5f, true);
    in.conv_wv = synth(seed_base + 10, c * p.conv_width, -0.5f, 0.5f, true);
    in.onorm_w = synth(seed_base + 11, p.head_dim, 0.5f, 1.5f, true);
    in.s0 = synth(seed_base + 12, static_cast<size_t>(p.num_heads) * p.head_dim * p.head_dim,
                  -1.0f, 1.0f, false);
    in.cs_q = synth(seed_base + 13, c * (p.conv_width - 1), -1.0f, 1.0f, true);
    in.cs_k = synth(seed_base + 14, c * (p.conv_width - 1), -1.0f, 1.0f, true);
    in.cs_v = synth(seed_base + 15, c * (p.conv_width - 1), -1.0f, 1.0f, true);
    return in;
}

struct ScanResult {
    std::vector<float> core, onorm;
    KdaState st;
    ConvState cq, ck, cv;
};

/// CPU end-to-end scan (conv -> scan -> o_norm) on the reference.
ScanResult run_ref_scan(const KdaParams& p, ScanPath path, const ScanInputs& in, int t_len) {
    ScanResult r;
    const size_t n = static_cast<size_t>(t_len) * p.channels();
    r.core.assign(n, 0.0f);
    r.onorm.assign(n, 0.0f);
    r.st = KdaState::zeros(p);
    if (!in.s0.empty()) r.st.s = in.s0;
    r.cq = ConvState::zeros(p);
    r.ck = ConvState::zeros(p);
    r.cv = ConvState::zeros(p);
    if (!in.cs_q.empty()) r.cq.ring = in.cs_q;
    if (!in.cs_k.empty()) r.ck.ring = in.cs_k;
    if (!in.cs_v.empty()) r.cv.ring = in.cs_v;
    kda_scan(p, path, in.q.data(), in.k.data(), in.v.data(), in.raw_g.data(), in.g2.data(),
             in.beta.data(), in.a_log.data(), in.dt_bias.data(), in.conv_wq.data(),
             in.conv_wk.data(), in.conv_wv.data(), in.onorm_w.data(), t_len, r.st, r.cq, r.ck,
             r.cv, r.core.data(), r.onorm.data());
    return r;
}

/// POST-conv input bundle for the scan/decode kernels: q/k/v are already what
/// the conv would have produced (bf16-valued fp32 — benign magnitudes, and
/// exactly representable so the CPU and GPU see the same numbers).
struct ScanKernelInputs {
    std::vector<float> q, k, v;   // post-conv fp32, [T][H*128]
    std::vector<float> raw_g;     // [T][H*128] bf16-valued
    std::vector<float> beta;      // [T][H] bf16-valued (pre-sigmoid)
    std::vector<float> g2;        // [T][H*128] bf16-valued
    std::vector<float> a_log;     // [H] fp32, NOT rounded
    std::vector<float> dt_bias;   // [H*128] fp32, NOT rounded
    std::vector<float> onorm_w;   // [128] bf16-valued
    std::vector<float> s0;        // [H][128][128] fp32, NOT rounded
};

ScanKernelInputs make_scan_kernel_inputs(int heads, int t_len, uint64_t seed) {
    const size_t c = static_cast<size_t>(heads) * D;
    const size_t n = static_cast<size_t>(t_len) * c;
    ScanKernelInputs in;
    in.q = synth(seed + 0, n, -1.0f, 1.0f, true);
    in.k = synth(seed + 1, n, -1.0f, 1.0f, true);
    in.v = synth(seed + 2, n, -1.0f, 1.0f, true);
    in.raw_g = synth(seed + 3, n, -3.0f, 3.0f, true);
    in.beta = synth(seed + 4, static_cast<size_t>(t_len) * heads, -2.0f, 2.0f, true);
    in.g2 = synth(seed + 5, n, -2.0f, 2.0f, true);
    in.a_log = synth(seed + 6, heads, -1.0f, 1.5f, false);
    in.dt_bias = synth(seed + 7, c, -1.0f, 1.0f, false);
    in.onorm_w = synth(seed + 8, D, 0.5f, 1.5f, true);
    in.s0 = synth(seed + 9, static_cast<size_t>(heads) * D * D, -1.0f, 1.0f, false);
    return in;
}

// ═══════════════════════════════════════════════════════════════════════════
// (iii) Short conv — launch_kda_conv_prefill / launch_kda_conv_decode
