        const auto b = download<float>(od[i], n);
        for (size_t j = 0; j < n; ++j) {
            ASSERT_EQ(a[j], b[j]) << "conv decode vs prefill out_" << tag[i] << " @" << j;
        }
        EXPECT_TRUE(bit_equal(download<float>(rp[i], rn), download<float>(rd[i], rn)))
            << "conv decode vs prefill ring_" << tag[i];
    }
}

// Slot indirection: a batch of 3 sequences writing into a 3-slot ring buffer
// through slots = {2,0,1} must match three independent single-sequence runs
// bitwise (same kernel, same arithmetic — only the addressing differs).
TEST(KdaConvKernel, DecodeBatchSlots) {
    REQUIRES_GPU();
    const int H = 4, B = 3;
    const KdaParams p = ref_params(H);
    const int C = p.channels();
    const size_t rn = static_cast<size_t>(C) * 3;
    const std::vector<int> slots = {2, 0, 1};

    DevBag bag;
    // One row of raw input per sequence, packed [B][C].
    const auto hxq = synth(44001, static_cast<size_t>(B) * C, -1.0f, 1.0f, true);
    const auto hxk = synth(44002, static_cast<size_t>(B) * C, -1.0f, 1.0f, true);
    const auto hxv = synth(44003, static_cast<size_t>(B) * C, -1.0f, 1.0f, true);
    const __nv_bfloat16* xq = bag.bf16(hxq);
    const __nv_bfloat16* xk = bag.bf16(hxk);
    const __nv_bfloat16* xv = bag.bf16(hxv);
    const __nv_bfloat16* wq = bag.bf16(synth(44004, static_cast<size_t>(C) * 4, -0.5f, 0.5f, true));
    const __nv_bfloat16* wk = bag.bf16(synth(44005, static_cast<size_t>(C) * 4, -0.5f, 0.5f, true));
    const __nv_bfloat16* wv = bag.bf16(synth(44006, static_cast<size_t>(C) * 4, -0.5f, 0.5f, true));

    // Distinct initial rings per sequence (GPU [3][C] layout).
    std::vector<std::vector<float>> r0q(B), r0k(B), r0v(B);
    for (int b = 0; b < B; ++b) {
        r0q[b] = ring_ref_to_gpu(synth(44010 + b, rn, -1.0f, 1.0f, true), C);
        r0k[b] = ring_ref_to_gpu(synth(44020 + b, rn, -1.0f, 1.0f, true), C);
        r0v[b] = ring_ref_to_gpu(synth(44030 + b, rn, -1.0f, 1.0f, true), C);
    }

    // Batched arm: [3 slots][3][C] ring buffers, sequence b living in slots[b].
    std::vector<float> packq(rn * B, 0.0f), packk(rn * B, 0.0f), packv(rn * B, 0.0f);
    for (int b = 0; b < B; ++b) {
        const size_t off = static_cast<size_t>(slots[b]) * rn;
        std::copy(r0q[b].begin(), r0q[b].end(), packq.begin() + off);
        std::copy(r0k[b].begin(), r0k[b].end(), packk.begin() + off);
        std::copy(r0v[b].begin(), r0v[b].end(), packv.begin() + off);
    }
    float* brq = bag.f32(packq);
    float* brk = bag.f32(packk);
    float* brv = bag.f32(packv);
    float* boq = bag.f32z(static_cast<size_t>(B) * C);
    float* bok = bag.f32z(static_cast<size_t>(B) * C);
    float* bov = bag.f32z(static_cast<size_t>(B) * C);
    {
        sl::KdaConvDecodeParams dp{};
        dp.x_q = xq; dp.x_k = xk; dp.x_v = xv;
        dp.w_q = wq; dp.w_k = wk; dp.w_v = wv;
        dp.ring_q = brq; dp.ring_k = brk; dp.ring_v = brv;
        dp.slots = bag.i32(slots);
        dp.ring_slot_stride = static_cast<int64_t>(rn);
        dp.out_q = boq; dp.out_k = bok; dp.out_v = bov;
        dp.batch = B;
        dp.channels = C;
        lc::launch_kda_conv_decode(dp, nullptr);
    }

    // Reference arm: one launch per sequence into its own single-slot buffer.
    std::vector<float*> srq(B), srk(B), srv(B), soq(B), sok(B), sov(B);
    for (int b = 0; b < B; ++b) {
        srq[b] = bag.f32(r0q[b]);
        srk[b] = bag.f32(r0k[b]);
        srv[b] = bag.f32(r0v[b]);
        soq[b] = bag.f32z(C);
        sok[b] = bag.f32z(C);
        sov[b] = bag.f32z(C);
        sl::KdaConvDecodeParams dp{};
        dp.x_q = xq + static_cast<size_t>(b) * C;
        dp.x_k = xk + static_cast<size_t>(b) * C;
        dp.x_v = xv + static_cast<size_t>(b) * C;
        dp.w_q = wq; dp.w_k = wk; dp.w_v = wv;
        dp.ring_q = srq[b]; dp.ring_k = srk[b]; dp.ring_v = srv[b];
        dp.slots = nullptr;
        dp.ring_slot_stride = static_cast<int64_t>(rn);
        dp.out_q = soq[b]; dp.out_k = sok[b]; dp.out_v = sov[b];
        dp.batch = 1;
        dp.channels = C;
        lc::launch_kda_conv_decode(dp, nullptr);
    }
    ASSERT_EQ(cudaDeviceSynchronize(), cudaSuccess);

    const auto gq = download<float>(brq, rn * B);
    const auto gk = download<float>(brk, rn * B);
    const auto gv = download<float>(brv, rn * B);
    const auto oq = download<float>(boq, static_cast<size_t>(B) * C);
    const auto ok = download<float>(bok, static_cast<size_t>(B) * C);
    const auto ov = download<float>(bov, static_cast<size_t>(B) * C);
    for (int b = 0; b < B; ++b) {
        const size_t roff = static_cast<size_t>(slots[b]) * rn;
        const size_t coff = static_cast<size_t>(b) * C;
        const auto rq1 = download<float>(srq[b], rn);
        const auto rk1 = download<float>(srk[b], rn);
        const auto rv1 = download<float>(srv[b], rn);
        const auto oq1 = download<float>(soq[b], C);
        const auto ok1 = download<float>(sok[b], C);
        const auto ov1 = download<float>(sov[b], C);
        for (size_t i = 0; i < rn; ++i) {
            ASSERT_EQ(gq[roff + i], rq1[i]) << "batch ring_q b=" << b << " @" << i;
            ASSERT_EQ(gk[roff + i], rk1[i]) << "batch ring_k b=" << b << " @" << i;
            ASSERT_EQ(gv[roff + i], rv1[i]) << "batch ring_v b=" << b << " @" << i;
        }
        for (int c = 0; c < C; ++c) {
            ASSERT_EQ(oq[coff + c], oq1[c]) << "batch out_q b=" << b << " @" << c;
            ASSERT_EQ(ok[coff + c], ok1[c]) << "batch out_k b=" << b << " @" << c;
            ASSERT_EQ(ov[coff + c], ov1[c]) << "batch out_v b=" << b << " @" << c;
        }
    }
}

