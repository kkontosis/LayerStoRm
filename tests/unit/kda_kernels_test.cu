        dp.w_q = wq; dp.w_k = wk; dp.w_v = wv;
        dp.ring_q = rd[0]; dp.ring_k = rd[1]; dp.ring_v = rd[2];
        dp.slots = nullptr;
        dp.ring_slot_stride = static_cast<int64_t>(3) * C;
        dp.out_q = od[0] + static_cast<size_t>(t) * C;
        dp.out_k = od[1] + static_cast<size_t>(t) * C;
        dp.out_v = od[2] + static_cast<size_t>(t) * C;
        dp.batch = 1;
        dp.channels = C;
